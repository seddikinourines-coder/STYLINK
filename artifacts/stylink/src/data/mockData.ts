export function defaultProjectStages(): ProjectStage[] {
  return PROJECT_STAGE_DEFS.map((d) => ({
    key: d.key,
    status: "not-started" as ProjectStageStatus,
    assignedIds: [],
    comments: [],
  }));
}

/** Today as YYYY-MM-DD (local). */
export function todayISO(): string {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

/**
 * Sequential workflow gate: a stage with status "not-started" can only be
 * started once every earlier stage in the canonical PROJECT_STAGE_DEFS order
 * is "completed". Already-running or completed stages are never blocked.
 *
 * Returns the canonical title of the first earlier stage that is still not
 * completed (so the UI can say "Attendez la fin de l'étape « Design »"),
 * or null if the stage can be freely started.
 */
export function blockingStageTitle(
  p: Project,
  targetKey: ProjectStageKey,
): string | null {
  const targetIdx = PROJECT_STAGE_DEFS.findIndex((d) => d.key === targetKey);
  if (targetIdx <= 0) return null; // first stage, never blocked
  for (let i = 0; i < targetIdx; i++) {
    const def = PROJECT_STAGE_DEFS[i];
    const stage = p.stages.find((s) => s.key === def.key);
    if (!stage || stage.status !== "completed") {
      return def.title;
    }
  }
  return null;
}

/** Derive a project's status from its stages + deadline (auto-computed). */
export function deriveProjectStatus(p: Project): ProjectStatus {
  if (p.stages.length > 0 && p.stages.every((s) => s.status === "completed")) {
    return "completed";
  }
  const today = todayISO();
  const overdueStage = p.stages.some(
    (s) => s.status !== "completed" && s.deadline && s.deadline < today,
  );
  const overdueOverall =
    !!p.deadline && p.deadline < today && p.stages.some((s) => s.status !== "completed");
  if (overdueStage || overdueOverall) return "delayed";
  return "active";
}

