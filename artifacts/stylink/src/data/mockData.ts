function generateProducts(): Product[] {
  const out: Product[] = [];
  for (const designer of mockDesigners) {
    const pool = designer.type === "Fournisseur" ? productPools.fabrics : productPools.apparel;
    const mix = mixByType[designer.type];
    // counter per category to advance through templates
    const cursor: Record<string, number> = {};
    mix.forEach((cat, idx) => {
      const slot = pool.find((p) => p.category === cat) ?? pool[0];
      const i = (cursor[cat] ?? 0) % slot.templates.length;
      cursor[cat] = i + 1;
      const tpl = slot.templates[i];
      const img = slot.images[i % slot.images.length];
      // small price variance per designer (±15%) using deterministic hash
      const priceJitter = 1 + ((designer.id.length * (idx + 1)) % 31 - 15) / 100;
      out.push({
        id: `${designer.id}-p${idx + 1}`,
        designerId: designer.id,
        name: tpl.name,
        price: Math.round((tpl.price * priceJitter) / 500) * 500,
        category: slot.category,
        image: img,
        description: tpl.desc,
        isNew: idx < 2,
      });
    });
  }
  return out;
}

